/**
 * Generate a ModBundle TS module from mods/<id>/ or a given directory.
 *
 * Usage (from packages/engine):
 *   bun scripts/gen-mod-bundle.ts --dir ../../docs/examples/mods/demo-pavilion --out ./src/generated-demo-mod.ts
 */
import { readFile, readdir } from "node:fs/promises";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { parse as parseYaml } from "yaml";

const engineRoot = join(fileURLToPath(new URL("..", import.meta.url)));

async function walkFiles(base: string, dir: string, out: Record<string, string>): Promise<void> {
  let entries;
  try {
    entries = await readdir(dir, { withFileTypes: true });
  } catch {
    return;
  }
  for (const ent of entries) {
    const full = join(dir, ent.name);
    if (ent.isDirectory()) await walkFiles(base, full, out);
    else if (ent.isFile() && ent.name !== "mod.yaml") {
      const rel = relative(base, full).replaceAll("\\", "/");
      out[rel] = await readFile(full, "utf8");
    }
  }
}

function serializeValue(value: unknown, indent: number): string {
  if (value === undefined) return "undefined";
  const pad = " ".repeat(indent);
  if (value === null) return "null";
  if (typeof value === "string") return JSON.stringify(value);
  if (typeof value === "number" || typeof value === "boolean") return String(value);
  if (Array.isArray(value)) {
    if (value.length === 0) return "[]";
    return `[\n${value.map((v) => `${pad}  ${serializeValue(v, indent + 2)},`).join("\n")}\n${pad}]`;
  }
  if (typeof value === "object") {
    const entries = Object.entries(value as Record<string, unknown>);
    if (entries.length === 0) return "{}";
    return `{\n${entries.map(([k, v]) => `${pad}  ${/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k)}: ${serializeValue(v, indent + 2)},`).join("\n")}\n${pad}}`;
  }
  return JSON.stringify(value);
}

export async function buildModBundleObject(modDir: string): Promise<Record<string, unknown>> {
  const manifestText = await readFile(join(modDir, "mod.yaml"), "utf8");
  const manifest = parseYaml(manifestText);
  const files: Record<string, string> = {};
  for (const ent of await readdir(modDir, { withFileTypes: true })) {
    if (ent.isDirectory()) await walkFiles(modDir, join(modDir, ent.name), files);
  }
  return { manifest, files };
}

async function main(): Promise<void> {
  const args = process.argv.slice(2);
  let dir = join(engineRoot, "../../docs/examples/mods/demo-pavilion");
  let out = join(engineRoot, "src/generated-demo-mod.ts");
  for (let i = 0; i < args.length; i++) {
    if (args[i] === "--dir") dir = args[++i]!;
    if (args[i] === "--out") out = args[++i]!;
  }
  const bundle = await buildModBundleObject(dir);
  const body = serializeValue(bundle, 0);
  const src = `/** Generated by scripts/gen-mod-bundle.ts — do not edit by hand. */\nimport type { ModBundle } from "./mod.ts";\n\nexport const demoPavilionMod = ${body} as ModBundle;\n`;
  await Bun.write(out, src);
  console.log(`wrote ${out}`);
}

if (import.meta.main) {
  await main();
}
